def _landscape_diagram(d, key, caption):
    d.landscape()
    d.h1("Диаграмма")
    d.p("Ниже приведена полная диаграмма в альбомной ориентации. Исходный файл "
        "для редактирования лежит рядом с документом в папке «Диаграммы».")
    d.figure_fit(diag(key), caption, max_w=25.7, max_h=15.0)
    d.p("Файл диаграммы: `04_Проектирование и UML/Диаграммы/"
        + os.path.basename(diag(key)) + "`; редактируемая версия — с расширением `.drawio`.",
        size=11, indent=False)
    d.portrait()


