def boss_rows():
    return [[i, b["name"], b["hp"], b["speed"], b["time"],
             ", ".join(FLAG_RU.get(f, f) for f in b["flags"]) or "—"]
            for i, b in enumerate(BOSSES, 1)]


def theme_rows():
    return [[i, t["name"], t["kills"], t["kind"]] for i, t in enumerate(THEMES, 1)]


def upgrade_rows():
    return [[TAB_NAMES[u["tab"]], u["name"], u["base"], u["growth"], u["max"]]
            for u in UPGRADES]


def item_rows():
    return [[i["name"], i["price"], i["dur"] or "—", i["desc"]] for i in ITEMS]


def relic_rows():
    return [[r["name"], RARITY_RU.get(r["rarity"], r["rarity"]), r["desc"]]
            for r in P.RELICS]


def tree_rows():
    return [[TREE_BRANCH.get(u["b"], u["b"]), u["name"], u["desc"], u["maxl"], u["base"]]
            for u in P.META_UPGRADES]


def ach_rows():
    return [[i, a["name"], a["desc"]] for i, a in enumerate(P.ACHIEVEMENTS, 1)]


def mod_rows():
    return [[m["name"], m["desc"]]
            for m in P.RUN_MODS]


def skin_rows():
    return [[i, s["name"]] for i, s in enumerate(SKINS, 1)]


def passenger_rows():
    return [[KIND_RU[k], KIND_HP[k], KIND_VALUE[k]]
            for k in KIND_HP]

