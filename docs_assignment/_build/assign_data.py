# Глубина вложенности сохранена: скрипт считает ROOT как три уровня выше себя.
SRC_EXTRA = [("docs/_tools/verify_content.py", "tests/_tools/verify_content.py")]
SRC_TREES = ["taran", "mobile"]
SRC_SKIP_DIRS = {"__pycache__", "build", "cdn_cache", "intro_frames",
                 "sound", "fonts", "taran", ".apkbuild"}
SRC_SKIP_EXT = {".pyc", ".pyo", ".apk", ".idsig", ".wav", ".ogg", ".mp3", ".ttf"}
SRC_NOTE = (
    "mobile/taran — рабочая копия пакета taran для сборки APK, поэтому в комплект "
    "не включена: настоящий код лежит в taran/. Так же пропущены каталоги "
    "mobile/build (APK 391 МБ), mobile/cdn_cache, mobile/intro_frames, mobile/sound "
    "и mobile/fonts — это двоичные материалы сборки, а не исходный код."
)


def _iter_source_files():
    for rel in SRC_FILES:
        if os.path.exists(os.path.join(ROOT, rel)):
            yield rel, rel
    for rel_src, rel_dst in SRC_EXTRA:
        if os.path.exists(os.path.join(ROOT, rel_src)):
            yield rel_src, rel_dst
    for tree in SRC_TREES:
        base = os.path.join(ROOT, tree)
        for dirpath, dirnames, filenames in os.walk(base):
            dirnames[:] = sorted(d for d in dirnames if d not in SRC_SKIP_DIRS)
            for fname in sorted(filenames):
                ext = os.path.splitext(fname)[1].lower()
                if ext in SRC_SKIP_EXT:
                    continue
                src = os.path.join(dirpath, fname)
                rel = os.path.relpath(src, ROOT)
                yield rel, rel.replace(os.sep, "/")


def prepare_sources():
    """Копирует в комплект фактический исходный код версии 3.2."""
    if os.path.isdir(SRC_OUT):
        shutil.rmtree(SRC_OUT)
    os.makedirs(SRC_OUT, exist_ok=True)

    rows = []
    py_lines = 0
    py_files = 0
    for rel_src, rel_dst in _iter_source_files():
        src = os.path.join(ROOT, rel_src)
        dst = os.path.join(SRC_OUT, rel_dst)
        os.makedirs(os.path.dirname(dst), exist_ok=True)
        shutil.copyfile(src, dst)
        size = os.path.getsize(dst)
        lines = "—"
        if rel_dst.endswith(".py"):
            try:
                with open(dst, encoding="utf-8") as f:
                    n = sum(1 for _ in f)
                py_lines += n
                py_files += 1
                lines = str(n)
            except OSError:
                pass
        rows.append((rel_dst, lines, size))

    lines_out = [
        "СПИСОК ФАЙЛОВ ИСХОДНОГО КОДА",
        "Проект: «ТАРАН-ЭКСПРЕСС» (Taran Express), версия %s" % VERSION,
        "Автор: %s, группа %s" % (AUTHOR, GROUP),
        "Дата сборки комплекта: %s" % DATE,
        "Всего файлов: %d, из них Python: %d, строк Python: %d" % (
            len(rows), py_files, py_lines),
        "",
        "Запуск из этой папки:  py game.py",
        "Проверки:  py test_smoke.py   |   py _meta_test.py   |   py tests/_tools/verify_content.py",
        "",
        SRC_NOTE,
        "",
        "%-42s %8s %10s" % ("файл", "строк", "байт"),
        "-" * 62,
    ]
    for rel_dst, lines, size in rows:
        lines_out.append("%-42s %8s %10d" % (rel_dst, lines, size))
    lines_out.append("-" * 62)
    lines_out.append("Итого: %d файлов, %d строк Python" % (len(rows), py_lines))
    with open(os.path.join(SRC_OUT, "_СПИСОК_ФАЙЛОВ.txt"), "w",
              encoding="utf-8", newline="\r\n") as f:
        f.write("\n".join(lines_out) + "\n")
    return len(rows), py_lines


