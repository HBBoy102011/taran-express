def _blank():
    s = prs.slides.add_slide(prs.slide_layouts[6])
    bg = s.shapes.add_shape(MSO_SHAPE.RECTANGLE, 0, 0, prs.slide_width, prs.slide_height)
    bg.fill.solid()
    bg.fill.fore_color.rgb = BG
    bg.line.fill.background()
    bg.shadow.inherit = False
    return s


def rect(s, x, y, w, h, fill=SURF, line=None, radius=True, alpha=None):
    shp = s.shapes.add_shape(MSO_SHAPE.ROUNDED_RECTANGLE if radius else MSO_SHAPE.RECTANGLE,
                             Inches(x), Inches(y), Inches(w), Inches(h))
    if radius:
        try:
            shp.adjustments[0] = 0.06
        except Exception:
            pass
    if fill is None:
        shp.fill.background()
    else:
        shp.fill.solid()
        shp.fill.fore_color.rgb = fill
    if line:
        shp.line.color.rgb = line
        shp.line.width = Pt(1)
    else:
        shp.line.fill.background()
    shp.shadow.inherit = False
    return shp


def text(s, x, y, w, h, run, size=18, color=TEXT, bold=False, align=PP_ALIGN.LEFT,
         anchor=MSO_ANCHOR.TOP, line_spacing=1.1, font=FONT):
    tb = s.shapes.add_textbox(Inches(x), Inches(y), Inches(w), Inches(h))
    tf = tb.text_frame
    tf.word_wrap = True
    tf.vertical_anchor = anchor
    tf.margin_left = 0
    tf.margin_right = 0
    tf.margin_top = 0
    tf.margin_bottom = 0
    p = tf.paragraphs[0]
    p.alignment = align
    p.line_spacing = line_spacing
    r = p.add_run()
    r.text = run
    r.font.size = Pt(size)
    r.font.bold = bold
    r.font.color.rgb = color
    r.font.name = font
    return tb


def bullet_box(s, x, y, w, h, items, size=16, gap=8, color=TEXT, marker_col=BLUE):
    tb = s.shapes.add_textbox(Inches(x), Inches(y), Inches(w), Inches(h))
    tf = tb.text_frame
    tf.word_wrap = True
    tf.margin_left = 0
    tf.margin_top = 0
    for i, item in enumerate(items):
        p = tf.paragraphs[0] if i == 0 else tf.add_paragraph()
        p.space_after = Pt(gap)
        p.line_spacing = 1.12
        m = p.add_run()
        m.text = "•  "
        m.font.size = Pt(size)
        m.font.color.rgb = marker_col
        m.font.name = FONT
        if isinstance(item, tuple):
            head, rest = item
            r1 = p.add_run()
            r1.text = head + " "
            r1.font.size = Pt(size)
            r1.font.bold = True
            r1.font.color.rgb = color
            r1.font.name = FONT
            r2 = p.add_run()
            r2.text = rest
            r2.font.size = Pt(size)
            r2.font.color.rgb = DIM
            r2.font.name = FONT
        else:
            r = p.add_run()
            r.text = item
            r.font.size = Pt(size)
            r.font.color.rgb = DIM
            r.font.name = FONT
    return tb


def slide(title, sub=None, accent=BLUE, num=None):
    s = _blank()
    bar = rect(s, 0, 0, W, 0.09, fill=accent, radius=False)
    bar.line.fill.background()
    text(s, 0.62, 0.36, 11.8, 0.62, title, 32, TEXT, True)
    if sub:
        text(s, 0.62, 0.98, 11.8, 0.4, sub, 15, DIM)
    if num is not None:
        text(s, 12.1, 7.02, 0.7, 0.3, "%02d" % num, 11, MUTED, align=PP_ALIGN.RIGHT)
        text(s, 0.62, 7.02, 8.0, 0.3, "ТАРАН-ЭКСПРЕСС  ·  версия 3.2", 10, MUTED)
    return s


def pic(s, path, x, y, w, h, border=True):
    iw, ih = Image.open(path).size
    k = min(w / iw, h / ih)
    pw, ph = iw * k, ih * k
    px = x + (w - pw) / 2
    py = y + (h - ph) / 2
    if border:
        rect(s, px - 0.05, py - 0.05, pw + 0.1, ph + 0.1, fill=None, line=LINE)
    s.shapes.add_picture(path, Inches(px), Inches(py), Inches(pw), Inches(ph))


def card(s, x, y, w, h, big, label, accent=BLUE, note=None):
    rect(s, x, y, w, h, fill=SURF, line=LINE)
    stripe = rect(s, x, y + 0.12, 0.06, h - 0.24, fill=accent, radius=False)
    stripe.line.fill.background()
    text(s, x + 0.26, y + 0.18, w - 0.4, 0.62, big, 30, accent, True)
    text(s, x + 0.26, y + 0.78, w - 0.4, 0.4, label, 13, TEXT, True)
    if note:
        text(s, x + 0.26, y + 1.14, w - 0.4, h - 1.24, note, 11, DIM)


